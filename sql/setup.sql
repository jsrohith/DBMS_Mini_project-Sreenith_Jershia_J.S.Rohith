-- Demo PL/SQL function and procedure for the college project.
CREATE OR REPLACE FUNCTION SHOPDEMO_ORDER_TOTAL (p_order_id IN NUMBER)
RETURN NUMBER
IS v_total NUMBER(12,2);
BEGIN
  SELECT NVL(SUM(QUANTITY * UNIT_PRICE),0) INTO v_total
  FROM SHOPDEMO_ORDER_ITEMS WHERE ORDER_ID = p_order_id;
  RETURN v_total;
END;
