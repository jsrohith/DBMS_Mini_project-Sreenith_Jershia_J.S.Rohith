-- These SHOPDEMO_ names are separate from your existing project tables.
CREATE TABLE SHOPDEMO_USERS (
  USER_ID NUMBER(10) PRIMARY KEY,
  USERNAME VARCHAR2(80) NOT NULL,
  EMAIL VARCHAR2(160) NOT NULL,
  PASSWORD_TEXT VARCHAR2(200) NOT NULL,
  FULL_NAME VARCHAR2(160),
  CONTACT VARCHAR2(40),
  CONSTRAINT SHOPDEMO_USERS_U1 UNIQUE (USERNAME),
  CONSTRAINT SHOPDEMO_USERS_U2 UNIQUE (EMAIL)
);
CREATE SEQUENCE SHOPDEMO_USER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SHOPDEMO_PRODUCTS (
  PRODUCT_ID NUMBER(10) PRIMARY KEY,
  NAME VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  PRICE NUMBER(10,2) NOT NULL,
  CATEGORY VARCHAR2(80),
  IMAGE_URL VARCHAR2(500)
);
CREATE SEQUENCE SHOPDEMO_PRODUCT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SHOPDEMO_CART (
  USER_ID NUMBER(10) NOT NULL,
  PRODUCT_ID NUMBER(10) NOT NULL,
  QUANTITY NUMBER(3) DEFAULT 1 NOT NULL,
  CONSTRAINT SHOPDEMO_CART_PK PRIMARY KEY (USER_ID, PRODUCT_ID),
  CONSTRAINT SHOPDEMO_CART_USER_FK FOREIGN KEY (USER_ID) REFERENCES SHOPDEMO_USERS(USER_ID),
  CONSTRAINT SHOPDEMO_CART_PROD_FK FOREIGN KEY (PRODUCT_ID) REFERENCES SHOPDEMO_PRODUCTS(PRODUCT_ID)
);

CREATE TABLE SHOPDEMO_ORDERS (
  ORDER_ID NUMBER(10) PRIMARY KEY,
  USER_ID NUMBER(10) NOT NULL,
  ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
  TOTAL_AMOUNT NUMBER(12,2) NOT NULL,
  ADDRESS VARCHAR2(300) NOT NULL,
  CITY VARCHAR2(100) NOT NULL,
  STATUS VARCHAR2(30) DEFAULT 'PLACED' NOT NULL,
  CONSTRAINT SHOPDEMO_ORDER_USER_FK FOREIGN KEY (USER_ID) REFERENCES SHOPDEMO_USERS(USER_ID)
);
CREATE SEQUENCE SHOPDEMO_ORDER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SHOPDEMO_ORDER_ITEMS (
  ORDER_ITEM_ID NUMBER(10) PRIMARY KEY,
  ORDER_ID NUMBER(10) NOT NULL,
  PRODUCT_ID NUMBER(10) NOT NULL,
  QUANTITY NUMBER(3) NOT NULL,
  UNIT_PRICE NUMBER(10,2) NOT NULL,
  CONSTRAINT SHOPDEMO_ITEM_ORDER_FK FOREIGN KEY (ORDER_ID) REFERENCES SHOPDEMO_ORDERS(ORDER_ID),
  CONSTRAINT SHOPDEMO_ITEM_PRODUCT_FK FOREIGN KEY (PRODUCT_ID) REFERENCES SHOPDEMO_PRODUCTS(PRODUCT_ID)
);
CREATE SEQUENCE SHOPDEMO_ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

