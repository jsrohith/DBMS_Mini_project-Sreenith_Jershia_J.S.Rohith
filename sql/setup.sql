CREATE OR REPLACE PROCEDURE SHOPDEMO_ADD_PRODUCT (
  p_name IN VARCHAR2, p_description IN VARCHAR2, p_price IN NUMBER, p_category IN VARCHAR2
)
IS
BEGIN
  INSERT INTO SHOPDEMO_PRODUCTS(PRODUCT_ID,NAME,DESCRIPTION,PRICE,CATEGORY)
  VALUES(SHOPDEMO_PRODUCT_SEQ.NEXTVAL,p_name,p_description,p_price,p_category);
END;
